// Bundles the scripts that need npm dependencies (MCP SDK, zod) into dist/, one file each, so the
// Claude Code plugin, the Codex plugin and the Claude Desktop extension run without `npm install`.
// src/hook.mjs uses only node: built-ins and runs from src/ directly.
// usage: node scripts/build.mjs
import { copyFileSync, mkdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const version = JSON.parse(readFileSync(path.join(repo, "package.json"), "utf8")).version;
const entries = ["src/mcp-server.mjs", "src/capsule/continue.mjs", "src/capsule/export.mjs", "src/capsule/imported-store.mjs"];

// Several modules run their CLI when `import.meta.url` is the script node was started with. In a
// bundle every module shares the bundle's URL, so only the entry may keep that check.
const MAIN_CHECK = "process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]";
const VERSION_READ = 'JSON.parse(readFileSync(new URL("../../package.json", import.meta.url), "utf8")).version';

const sourceFixes = (entry) => ({
  name: "source-fixes",
  setup(b) {
    b.onLoad({ filter: /\.mjs$/ }, (args) => {
      if (!path.resolve(args.path).startsWith(path.join(repo, "src") + path.sep)) return undefined;
      let code = readFileSync(args.path, "utf8");
      if (path.resolve(args.path) !== entry) code = code.replaceAll(MAIN_CHECK, "false");
      code = code.replaceAll(VERSION_READ, JSON.stringify(version));
      if (code.includes("import.meta.url") && !code.includes(MAIN_CHECK)) {
        throw new Error(`${path.relative(repo, args.path)} uses import.meta.url in a way the bundle can't keep; update scripts/build.mjs`);
      }
      return { contents: code, loader: "js" };
    });
  }
});

for (const rel of entries) {
  const entry = path.join(repo, rel);
  await build({
    entryPoints: [entry],
    outfile: path.join(repo, "dist", path.basename(rel)),
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    legalComments: "eof",
    // CommonJS dependencies inside the bundle still call require().
    banner: { js: `// Generated by scripts/build.mjs from ${rel}; do not edit.\nimport { createRequire as __createRequire } from "node:module";\nconst require = __createRequire(import.meta.url);` },
    plugins: [sourceFixes(entry)],
    logLevel: "warning"
  });
  console.log(`built dist/${path.basename(rel)}`);
}

// Claude Desktop extension: `npm run build:mcpb` packs this folder into dist/desktop-continuity.mcpb.
const ext = path.join(repo, "desktop-extension");
mkdirSync(path.join(ext, "server"), { recursive: true });
copyFileSync(path.join(repo, "dist", "mcp-server.mjs"), path.join(ext, "server", "mcp-server.mjs"));
for (const f of ["LICENSE", "NOTICE"]) copyFileSync(path.join(repo, f), path.join(ext, f));
console.log("staged desktop-extension/");
